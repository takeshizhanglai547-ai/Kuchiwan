/* =============================================================================
   ASHLINE / アートディレクションの単一の真実
   全モジュールは色をここからしか取らない。直接16進を書くことを禁じる。

   世界観（オリジナル。既存作品の固有名詞・意匠は一切使わない）
     場所：石と鉄筋コンクリートで築かれた旧市街の中央広場。砲撃戦の翌日。
     時刻：陽が低い午後遅く。空気中に粉塵が残り、逆光が層になって見える。
     絵の原則：彩度を落とした暖色の灰とオーカーで環境を作り、
               冷たい青灰＝自機側、鈍い酸化鉄の赤＝敵側の2色だけで陣営を分ける。
               画面の中で本当に彩度が高いのは「火」だけ。それ以外は必ず濁らせる。

   トーンマッピングは ACESFilmic。ACESは彩度と明度を落とすので、
   ここに置く値は「最終画面より少し明るく・少し強い」ものになっている。
   ========================================================================== */
(function (g) {
  var ASH = g.ASH = g.ASH || {};

  ASH.palette = {
    /* ---- 大気 ---------------------------------------------------------- */
    skyZenith: 0x2c333c,     // 天頂：冷たい青灰
    skyHorizon: 0x8a7a63,    // 地平：粉塵に沈んだオーカー
    skySun: 0xffcf9a,        // 太陽まわりの滲み
    fog: 0x6d6355,           // 霧＝地平と同系。遠景を必ず一段濁らせる
    fogNear: 16.0,
    fogFar: 78.0,
    dust: 0xbfae94,          // 空中の粉塵粒

    /* ---- 光 ------------------------------------------------------------ */
    /* 太陽。ライティング批評の実測に従って3点を変更した。
       (1) 色 0xffdcb0 は B/R=0.69 で暖色に寄りすぎ、順光では自機の装甲が
           RGB(200,169,123)＝暖色84.7%／寒色0.0% と陣営色が完全に反転していた。
           B/R=0.80 に上げる。失う暖色は skyHorizon と fog 側で作る。
       (2) 方向 (-0.62,0.38,-0.68) では、逆光構図でジオメトリの輝度0.75超が
           0.000%（明部を担っていたのは空と遠景の板だけ）。sun/hemi/exposure を
           8通り振っても 0.000% のままで、スカラー調整では原理的に直らなかった。
           斜めから舐める角度に変えると 0.002%→0.104% と50倍になり、
           暗部は1ポイントしか増えず彩度はむしろ下がる（批評の実測）。
       (3) 強度 2.35 では順光が median 0.3685 / 暗部13.7% で
           §3の不合格条件「全面均一な明るさ」に該当していた。 */
    sunColor: 0xffe8cc,
    /* 1.90 まで落としたら4方位のうち3方位で暗部が60%超になり暗くしすぎた。
       批評が実測で検証したのは「方向の変更のみ（強度2.35のまま）」だったので戻す。
       方向の変更だけで、最も明るい方位のジオメトリ最大輝度は 0.745 -> 0.811 に上がる。*/
    sunIntensity: 2.35,
    sunDir: { x: -0.90, y: 0.26, z: -0.35 },   // 低く、斜めから舐める
    ambientSky: 0x7f95ad,    // 上からの冷たい回り込み
    ambientGround: 0x4b453c, // 地面からの照り返し。暖色に寄せすぎると画面全体の彩度が上がる
    ambientIntensity: 0.95,  // 0.62では画面の41.9%が輝度0.04未満に潰れていた（実測）
    rimColor: 0xffc386,      // 擬似リムライト（シェーダで焼き込む）
    rimStrength: 0.42,       // light.js 側の適用範囲を広げる前提で総量を下げる
    aoStrength: 0.28,        // 擬似AO。0.45では暗部が形状情報を失っていた（実測）

    /* ---- 素材：環境 ---------------------------------------------------- */
    concrete: 0x9a9184,
    concreteDark: 0x5f584e,
    concreteWet: 0x474441,   // 濡れ／油染みの濃い部分
    plaster: 0xb5a894,       // 剥がれた漆喰
    stone: 0x8d8375,         // 切石
    brick: 0x7d6357,         // 露出した煉瓦。0x8a6450(sat 0.42)は日向で画面彩度0.51に達し、
                             // 火(フラッシュ芯 sat 0.09)より高かった
    rebar: 0x4a423a,         // 鉄筋
    metal: 0x6e6862,
    rust: 0x7a5940,          // 0x8f5730(sat 0.66)から落とす。理由は brick と同じ
    ground: 0x5c5449,
    groundDark: 0x3d372f,
    ash: 0x6a6259,           // 灰の堆積
    grime: 0x2a2521,         // 汚れの乗算色

    /* ---- 素材：陣営 ---------------------------------------------------- */
    // 自機：冷たい灰。彩度は環境（S≈0.14）に合わせ、識別は色相ではなく明度で行う。
    // 0x49535e は彩度0.223で環境より高く暖色の画面から青く浮いていた。
    // その後 0x55595e に落としたが、今度は暗色コンクリート(0x5f584e)と
    // 相対輝度がほぼ同一（コントラスト比1.005:1）で明度でも分離できていなかった（実測）。
    // 彩度は据え置いたまま明度だけを上げ、環境から抜く。
    playerArmor: 0x7c8288,
    playerArmorDark: 0x4d5257,
    playerCloth: 0x6d6353,
    playerTrim: 0x9aa6b2,

    /* 敵：鈍い酸化鉄。
       0x4a2a22 まで暗くしたのは誤りだった。背後の壁は hemi だけで相対輝度0.0067まで
       沈むため、敵をそこより暗くすると壁の「下」に潜り、画面実測のコントラスト比は
       1.03〜1.08:1 しかなかった（私はパレットの16進どうしの比1.713を見ていた）。
       自機との分離は明度ではなく彩度で取る（画面実測で自機 sat 0.089 / 敵 sat 0.42）。*/
    enemyArmor: 0x7a4638,
    enemyArmorDark: 0x452720,
    enemyCloth: 0x554438,
    enemyTrim: 0xa86b4b,

    /* ---- 火（画面で唯一彩度を許す色） ---------------------------------- */
    muzzleCore: 0xfff2d0,
    muzzleGlow: 0xffa03c,
    tracer: 0xffb862,
    ember: 0xff7a28,
    impactSpark: 0xffc978,
    bloodMist: 0x5e1c17,

    /* ---- UI ------------------------------------------------------------ */
    uiInk: 0xd8dde2,
    uiDim: 0x8b949d,
    uiWarn: 0xff8a4c,
    uiEnemy: 0xd85a3a,

    /* ---- ポスト --------------------------------------------------------- */
    /* ブルームは「画面を白く濁らせている」のではなく、逆に何もしていなかった。
       強度0.62→0のA/Bで画面平均の変化は逆光 -0.00025、暗部では ±0.00000。
       しきい値を0.50まで下げても地の明るさは0.0004しか動かない（＝濁る余地がない）。*/
    bloomThreshold: 0.55,
    bloomIntensity: 0.95,
    bloomRadius: 0.85,
    exposure: 1.12,
    vignette: 0.32
  };

  /* 使い勝手：0xRRGGBB -> THREE.Color を作るヘルパ（Tはthreeの名前空間） */
  ASH.col = function (T, hex) { return new T.Color(hex); };

  /* 明度をずらした派生色。素材の面ごとの差を作るのに使う。 */
  ASH.shade = function (T, hex, mul) {
    var c = new T.Color(hex);
    c.multiplyScalar(mul);
    return c;
  };
})(typeof window !== 'undefined' ? window : globalThis);
