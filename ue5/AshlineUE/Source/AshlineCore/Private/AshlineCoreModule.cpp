/* ==========================================================================
   AshlineCoreModule.cpp — UEのモジュール機構に対する入口。ここだけの例外。

   なぜこの1ファイルだけUEに触れるのか
     AshlineCore は「UEに依存しない」ことを設計の要にしている。UEが無いこの
     環境でルールを実際に走らせて検証できるのは、その独立性のおかげ。
     しかし .uproject に載ったモジュールは、起動時に FModuleManager が
     必ずロードしようとする。IMPLEMENT_MODULE が無いと登録先が存在せず、
     「AshlineCore が見つからないか、別バージョンでビルドされています」と出て
     エディタが開かない。しかもその画面の「リビルド」を押しても、同じバイナリが
     できるだけなので永久に直らない。ビルドに10〜40分かけた後で起きる。

     bRequiresImplementModule = false は UnrealBuildTool のビルド時チェックを
     黙らせるだけで、実行時のロードには何の効果も無い。

   したがって、入口だけをこの1ファイルに閉じ込める。
   ゲームのルールは1行も置かない。検証時の clang ビルドからは、
   ue5/tests/run.sh がこのファイルだけを明示的に除外する。
   ========================================================================== */
#include "Modules/ModuleManager.h"

IMPLEMENT_MODULE(FDefaultModuleImpl, AshlineCore);
